#include<stdio.h>
int main() {
     int radius = 14;
     float pi = 3.14;

     float Area = pi * radius * radius;
     float Circumference = 2 * pi * radius;

     printf(" The area of the circle is: %f\n", Area);
     printf(" Circumference of the circle is: %f\n", Circumference);

     return 0;
    
}